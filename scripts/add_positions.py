def main():
    with open(PATH, encoding="utf-8") as f:
        data = json.load(f)
    added = []
    for name, body in NEW.items():
        if name in data["positions"]:
            print("已存在，跳过：", name)
            continue
        data["positions"][name] = body
        added.append(name)
    with open(PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print("新增岗位：", added)
    print("当前岗位：", list(data["positions"].keys()))

    # 校验占比合计
    for name, body in NEW.items():
        s = sum(t["占比"] for t in body["written"]["考点分布"])
        n = sum(t["题量"] for t in body["written"]["考点分布"])
        ts = sum(body["written"]["题型分布"].values())
        print(f"{name}: 考点占比合计 {s:.2f}，题量合计 {n}，题型合计 {ts:.2f}")


if __name__ == "__main__":
    main()
